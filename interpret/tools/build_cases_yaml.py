"""
Build interpret/cases/cases.yaml from interpret/cases/pairs.csv.

Selection (all cases):   X-ray, resolution <= --max_res, Davis pKd >= --min_y
                         (5.0 is Davis' "no binding detected" floor), k-mer
                         containment >= --min_cont (guards against paralog hits).
Core subset (tier=core): at most --per_drug pairs per drug and --per_protein per
                         protein (highest affinity, then best resolution), so that
                         promiscuous ligands such as staurosporine do not dominate.
Main-figure cases are set with --main "drug_name:GENE" (case-insensitive) or edited
by hand afterwards (main_figure: true).

Drug names come from the RCSB chemical component name (network, cached in pairs.csv).
"""
import os
import argparse

import pandas as pd
import requests
import yaml

GRAPHQL_URL = "https://data.rcsb.org/graphql"


def comp_names(comp_ids):
    q = """query($ids:[String!]!){ chem_comps(comp_ids:$ids){ chem_comp{ id name }
             rcsb_chem_comp_synonyms{ name provenance_source } } }"""
    r = requests.post(GRAPHQL_URL, json={"query": q, "variables": {"ids": list(comp_ids)}}, timeout=60)
    r.raise_for_status()
    out = {}
    for c in r.json()["data"]["chem_comps"]:
        if not c:
            continue
        name = c["chem_comp"]["name"]
        syn = [s["name"] for s in (c.get("rcsb_chem_comp_synonyms") or [])
               if s.get("name") and len(s["name"]) < 25 and " " not in s["name"]]
        short = sorted(syn, key=len)[0] if syn else name
        out[c["chem_comp"]["id"]] = (name, short)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases_dir", default="interpret/cases")
    ap.add_argument("--max_res", type=float, default=3.0)
    ap.add_argument("--min_y", type=float, default=6.0)
    ap.add_argument("--min_cont", type=float, default=0.90)
    ap.add_argument("--per_drug", type=int, default=4)
    ap.add_argument("--per_protein", type=int, default=2)
    ap.add_argument("--main", nargs="*", default=[])
    args = ap.parse_args()

    p = pd.read_csv(os.path.join(args.cases_dir, "pairs.csv"), dtype={"drug_id": str, "protein_id": str})
    if "comp_name" not in p or p.comp_name.isna().any():
        names = comp_names(sorted(p.comp_id.unique()))
        p["comp_name"] = p.comp_id.map(lambda c: names.get(c, ("", ""))[0])
        p["drug_short"] = p.comp_id.map(lambda c: names.get(c, ("", ""))[1])
        p.to_csv(os.path.join(args.cases_dir, "pairs.csv"), index=False)

    sel = p[(p.resolution <= args.max_res) & (p.y >= args.min_y) & (p.kmer_containment >= args.min_cont)].copy()
    sel = sel.sort_values(["y", "resolution"], ascending=[False, True])

    core_idx, n_drug, n_prot = [], {}, {}
    for i, r in sel.iterrows():
        if n_drug.get(r.drug_id, 0) < args.per_drug and n_prot.get(r.protein_id, 0) < args.per_protein:
            core_idx.append(i)
            n_drug[r.drug_id] = n_drug.get(r.drug_id, 0) + 1
            n_prot[r.protein_id] = n_prot.get(r.protein_id, 0) + 1
    sel["tier"] = "extended"
    sel.loc[core_idx, "tier"] = "core"

    main_keys = {m.lower() for m in args.main}
    cases = []
    for _, r in sel.iterrows():
        drug_name = r.drug_short or r.comp_name
        key = f"{str(drug_name).lower()}:{str(r.protein_gene).lower()}"
        cid = f"{r.pdb_id}_{r.comp_id}_{r.protein_gene}".replace("/", "-").replace(" ", "")
        cases.append({
            "case_id": cid, "dataset": "davis", "tier": r.tier,
            "main_figure": key in main_keys or f"{r.pdb_id.lower()}" in main_keys,
            "drug_id": r.drug_id, "drug_name": str(drug_name), "comp_id": r.comp_id,
            "protein_id": r.protein_id, "protein_gene": r.protein_gene,
            "pdb_id": r.pdb_id, "resolution": float(r.resolution), "y": round(float(r.y), 4),
            "protein_chain": str(r.protein_chains).split(",")[0],
            "ligand_chain": None,
        })
    ov_path = os.path.join(args.cases_dir, "overrides.yaml")
    overrides = yaml.safe_load(open(ov_path)) if os.path.exists(ov_path) else {}
    overrides = overrides or {}
    extra = overrides.pop("extra_cases", []) or []
    for c in cases:
        c.update(overrides.get(c["case_id"], {}))
    existing_ids = {c["case_id"] for c in cases}
    for ec in extra:
        if ec["case_id"] not in existing_ids:
            cases.append(ec)
            existing_ids.add(ec["case_id"])
    with open(os.path.join(args.cases_dir, "cases.yaml"), "w") as f:
        f.write("# Auto-generated by interpret/tools/build_cases_yaml.py - edit main_figure / chains by hand if needed\n")
        yaml.safe_dump({"cases": cases}, f, sort_keys=False, allow_unicode=True)
    core = sel[sel.tier == "core"]
    print(f"{len(cases)} total cases ({len(core)} core pairs: {core.drug_id.nunique()} drugs, {core.protein_id.nunique()} proteins)")
    print("main_figure:", [c["case_id"] for c in cases if c["main_figure"]])


if __name__ == "__main__":
    main()
